passenger_demo = pd.Series(np.where(
    is_challenging_cbd, 'Students & Young Adults (18-25)',
    np.where(pickup_zones.isin(['Sandton Gautrain (Safe Zone)', 'Centurion Gautrain (Safe Zone)', 'OR Tambo / Intercity Long-Haul (45km+)']),
             'Corporate & Gautrain/Airport Travelers (26-55)',
    np.where(pickup_zones.isin(['Brooklyn & Pretoria East (Safe)', 'Rosebank Suburbs (Safe Zone)']),
             'Suburban & Nightlife Riders (21-45)', 'Public Transit Commuters (20-60)'))
), dtype='category')

std_dist = np.clip(np.round(np.random.lognormal(mean=2.08, sigma=0.56, size=N_TRIPS), 1), 2.0, 38.0)
air_dist = np.round(np.random.uniform(42.0, 85.0, size=N_TRIPS), 1)
trip_distances = np.where(pickup_zones == 'OR Tambo / Intercity Long-Haul (45km+)', air_dist, std_dist).astype(np.float32)

# Unpaid Pickup Distance (Calibrated to Screenshots: normal 0.5-3.5km, "Out of Radius" 8.0-17.7km)
is_out_of_radius = np.random.binomial(1, 0.18, size=N_TRIPS).astype(bool)
unpaid_pickup_km = np.where(is_out_of_radius, np.round(np.random.uniform(8.0, 17.7, size=N_TRIPS), 1),
                            np.round(np.random.uniform(0.5, 3.5, size=N_TRIPS), 1)).astype(np.float32)

df = pd.DataFrame({
    'Trip_ID': np.arange(1, N_TRIPS + 1, dtype=np.int32),
    'Driver_ID': np.random.choice(driver_ids, size=N_TRIPS),
    'Day_of_Month': dom, 'Day_of_Week_Num': dow, 'Hour': pickup_hours,
    'Is_Payday_Window': is_payday_trip, 'Is_Stadium_Event': is_event_trip,
    'Calendar_Period': calendar_period, 'Pickup_Zone': pickup_zones,
    'Zone_Category': zone_category, 'High_Risk_Zone': is_high_risk,
    'Passenger_Demographic': passenger_demo, 'Distance_km': trip_distances,
    'Unpaid_Pickup_km': unpaid_pickup_km, 'Is_Out_Of_Radius': is_out_of_radius,
    'Surge_Multiplier': surge_mult
}).merge(drivers_df, on='Driver_ID', how='left')

# 4. SCREENSHOT-CALIBRATED FINANCIAL MODELING (2016 vs. 2026 ALGORITHMIC DECAY)
rate_16 = df['Vehicle_Tier'].map({'Economy (Go)': 7.20, 'Standard (UberX/Bolt)': 8.00, 'Premium (Uber Black)': 14.50, 'Luxury Van (XL/Black)': 16.50}).astype(np.float32)
base_rate_26 = df['Vehicle_Tier'].map({'Economy (Go)': 3.90, 'Standard (UberX/Bolt)': 4.70, 'Premium (Uber Black)': 10.50, 'Luxury Van (XL/Black)': 12.50}).astype(np.float32)
dist_decay = np.where((df['Distance_km'] > 20.0) & (df['Vehicle_Tier'].isin(['Economy (Go)', 'Standard (UberX/Bolt)'])), 0.72, 1.00).astype(np.float32)
rate_26 = base_rate_26 * dist_decay

base_16 = df['Vehicle_Tier'].map({'Economy (Go)': 18.0, 'Standard (UberX/Bolt)': 20.0, 'Premium (Uber Black)': 40.0, 'Luxury Van (XL/Black)': 50.0}).astype(np.float32)
base_26 = df['Vehicle_Tier'].map({'Economy (Go)': 14.0, 'Standard (UberX/Bolt)': 18.0, 'Premium (Uber Black)': 38.0, 'Luxury Van (XL/Black)': 48.0}).astype(np.float32)
fuel_burn = df['Vehicle_Tier'].map({'Economy (Go)': 0.068, 'Standard (UberX/Bolt)': 0.082, 'Premium (Uber Black)': 0.105, 'Luxury Van (XL/Black)': 0.125}).astype(np.float32)

clean_multiplier = np.where(df['Regular_Car_Wash'], 1.12, 1.00).astype(np.float32)
df['Fare_2016_ZAR'] = np.round((base_16 + (df['Distance_km'] * rate_16)) * df['Surge_Multiplier'] * clean_multiplier, 2)
df['Fare_2026_ZAR'] = np.maximum(36.90, np.round((base_26 + (df['Distance_km'] * rate_26)) * df['Surge_Multiplier'] * clean_multiplier, 2))

deadhead_mult = np.where(df['Pickup_Zone'] == 'OR Tambo / Intercity Long-Haul (45km+)', 1.50, 1.00).astype(np.float32)
total_driven_km = (df['Distance_km'] * deadhead_mult) + df['Unpaid_Pickup_km']
df['Fuel_Cost_2016_ZAR'] = np.round(total_driven_km * fuel_burn * 12.50, 2)
df['Fuel_Cost_2026_ZAR'] = np.round(total_driven_km * fuel_burn * 28.50, 2)

df['Net_Driver_2016_ZAR'] = np.round((df['Fare_2016_ZAR'] * 0.80) - df['Fuel_Cost_2016_ZAR'], 2)
df['Net_Driver_2026_ZAR'] = np.round((df['Fare_2026_ZAR'] * 0.65) - df['Fuel_Cost_2026_ZAR'], 2)

# 5. SAFETY, WAIT TIMES, TAXI CHASES, POLICE VISIBILITY & TRACKER RECOVERY
df['Police_Visibility'] = pd.Series(np.random.choice(['Police Present', 'No Police Present'], size=N_TRIPS, p=[0.35, 0.65]), dtype='category')
base_wait = np.random.exponential(scale=4.2, size=N_TRIPS)
wait_extra = np.where(df['High_Risk_Zone'], np.random.uniform(5.5, 12.0, size=N_TRIPS), np.where(is_challenging_cbd, np.random.uniform(2.5, 6.0, size=N_TRIPS), 0.0))
df['Wait_Time_min'] = np.round(base_wait + wait_extra, 1).astype(np.float32)

vol_adj = np.where(df['Driver_Volume_Tier'] == 'Hit Target (500+ Trips/m)', -0.09, np.where(df['Driver_Volume_Tier'] == 'Low Volume (<300 Trips/m)', 0.08, 0.0))
panic_adj = np.where(df['Has_Panic_Button'], -0.15, 0.07)
police_adj = np.where(df['Police_Visibility'] == 'Police Present', -0.015, 0.0)

cancel_prob = np.clip(0.06 + (df['Wait_Time_min'] / 42.0) + np.where(df['High_Risk_Zone'], 0.52, np.where(is_challenging_cbd, 0.18, 0.0)) + vol_adj + panic_adj + police_adj, 0.03, 0.94)
df['Is_Cancelled'] = np.random.binomial(1, cancel_prob).astype(bool)

df['Security_Incident'] = np.where(df['High_Risk_Zone'], np.random.binomial(1, 0.16, size=N_TRIPS), np.random.binomial(1, 0.012, size=N_TRIPS)).astype(bool)
df['Escaped_Danger'] = np.where(df['Security_Incident'], np.random.binomial(1, np.where(df['Has_Panic_Button'], 0.89, 0.34)).astype(bool), True)
df['Vehicle_Recovered'] = np.where(df['Security_Incident'], np.random.binomial(1, np.where(df['Is_Tracked'], 0.92, 0.18)).astype(bool), True)

raw_ratings = np.random.normal(4.40, 0.25, N_TRIPS) + np.where(df['Regular_Car_Wash'], 0.38, -0.45)
df['Customer_Rating'] = np.where(df['Is_Cancelled'], np.nan, np.clip(np.round(raw_ratings, 1), 1.0, 5.0)).astype(np.float32)

print(f"✅ Master Dataset Ready! Rows: {len(df):,} | Memory Usage: {df.memory_usage().sum() / (1024**2):.1f} MB")

